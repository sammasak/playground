// On-device chat generation for the chess bot "personality chat" feature.
//
// ZERO server calls / ZERO third-party network. Everything runs on-device: a
// real in-browser BitNet I2_S LLM (bitnet-wasm) generates EVERY reply inside a
// Web Worker, fully DECOUPLED from gameplay.
//
// There are NO hardcoded/templated chess phrases anywhere in the product path.
// The ONLY non-LLM output is:
//   - A neutral status line while the model downloads/loads (NOT in character):
//       "🧠 Bot is warming up… (model NN% loaded)"
//   - Under force-mock (`?llm=mock` / `window.__BITNET_FORCE_MOCK`), a single
//     obvious sentinel string `[mock reply]` so Playwright stays deterministic
//     without downloading the ~880MB model. This is a test stub, not a product
//     phrase.
//
// STATEFUL CONVERSATION: the bot now holds a coherent MULTI-TURN chat. The
// worker keeps a persistent KV cache: the personality's system prompt is
// prefilled ONCE (via `chat_reset`) and every turn (via `chat_send`) is appended
// to that cache, so the bot remembers prior turns AND stays in character. When
// the personality changes or the game resets, we call `resetConversation()` to
// start a fresh session with the new persona / fresh game context.
//
// Public API:
//   - preloadLLM()                       — pre-warm the worker/model (page load).
//   - isLLMReady()                       — has the model finished loading?
//   - getLLMStatusText()                 — current warming-up status, or null.
//   - resetConversation(personality)     — start a fresh conversation with the
//         given persona's system prompt (resets the KV cache). Lazy: if the
//         model isn't ready yet the reset is deferred and applied on first use.
//   - generateReply({ personality, moves, fen, userMessage?, capture? })
//         -> Promise<string|null>. Resolves with a short, trimmed, in-character
//            reply generated by the LLM, or `null` if the model isn't ready yet
//            (caller decides whether to skip or show the warming-up status).
//
// The model file is hosted (same-origin) as GGUF chunks described by
//   `${BASE_URL}bitnet/model/manifest.json`  ->  { chunks: [...], bytes: N }
// The worker fetches each chunk, concatenates them, and instantiates the model.

import { PERSONALITIES, DEFAULT_PERSONALITY } from './personalities.js';

// Advertises which implementation is active. UI / e2e can read this.
export const LLM_MODE = 'wasm';

// Generation sizing: keep tokens SMALL for speed — replies are one short line.
// (Orchestrator may tune this alongside the template below.)
const MAX_TOKENS = 36;

// Sampling config for the small 2B on-device model. These are the
// experimentally-determined "balanced" settings: greedy decoding LOOPS
// ("it's a storm, and it's a storm…") and high temperature (>=0.75) produces
// GARBAGE ("2 do what 5"). temperature 0.5 / top_k 40 / top_p 0.9 /
// repeat_penalty 1.3 gives mostly-coherent, in-character one-liners. A FRESH
// random seed per turn makes replies vary run-to-run.
const SAMPLING = { temperature: 0.5, topK: 40, topP: 0.9, repeatPenalty: 1.3 };

// Draw a fresh 53-bit random seed (safe integer range) for each turn. The
// browser has real randomness; a per-turn seed keeps replies from repeating.
function freshSeed() {
  return Math.floor(Math.random() * 0x1fffffffffffff);
}

// The single sentinel returned under force-mock. Obvious test stub — NOT a
// product phrase, NOT chess trash-talk.
const MOCK_REPLY = '[mock reply]';

// Cap on the final trimmed reply length (characters).
const MAX_REPLY_CHARS = 120;

// Human-readable piece names (used only to describe a capture *situation* to
// the model — this is prompt context, NOT a canned reply).
const PIECE_LABEL = {
  pawn: 'pawn',
  knight: 'knight',
  bishop: 'bishop',
  rook: 'rook',
  queen: 'queen',
  king: 'king',
};

// --- Base URL resolution --------------------------------------------------
function resolveBase() {
  let base = '/';
  try {
    if (typeof import.meta !== 'undefined' && import.meta.env && import.meta.env.BASE_URL) {
      base = import.meta.env.BASE_URL;
    } else if (typeof document !== 'undefined') {
      const el = document.getElementById('chess-container');
      if (el && el.dataset && el.dataset.base) base = el.dataset.base;
    }
  } catch (e) {
    // ignore — default '/'
  }
  if (!base.endsWith('/')) base += '/';
  return base;
}

// --- Force-mock detection -------------------------------------------------
function forceMock() {
  try {
    if (typeof window !== 'undefined' && window.__BITNET_FORCE_MOCK === true) return true;
    if (typeof window !== 'undefined' && window.location) {
      const params = new URLSearchParams(window.location.search);
      if (params.get('llm') === 'mock') return true;
    }
  } catch (e) {
    // If anything goes wrong reading location, prefer mock (safe + fast).
    return true;
  }
  return false;
}

// ==========================================================================
// PROMPT CONSTRUCTION — the ONE place to tweak the template + situation text.
// The orchestrator may refine the exact wording / maxTokens here.
// ==========================================================================
//
// IMPORTANT: We deliberately DO NOT put the raw FEN in the prompt. A full FEN
// includes the castling field (e.g. "KQkq"), which the small model tends to
// echo and loop on ("KQKQKQ…"). Instead we build a SHORT natural-language board
// context: the last few moves plus an approximate material summary derived only
// from the piece-placement field (never the castling/turn fields).
//
// Relative point values used for the rough material summary.
const PIECE_VALUE = { p: 1, n: 3, b: 3, r: 5, q: 9, k: 0 };

// Compute a brief, natural-language material summary from a FEN's
// piece-placement field ONLY (the part before the first space). Never touches
// the castling/turn fields (that's what makes the model loop on "KQkq…").
// Returns something like "Material is roughly even" or "White is up a pawn".
function materialSummaryFromFen(fen) {
  if (!fen || typeof fen !== 'string') return 'Material is roughly even';
  const placement = fen.split(' ')[0]; // piece-placement field ONLY
  let white = 0;
  let black = 0;
  for (const ch of placement) {
    const lower = ch.toLowerCase();
    const val = PIECE_VALUE[lower];
    if (val == null) continue; // digits and '/' separators
    if (ch === lower) black += val;
    else white += val;
  }
  const diff = white - black;
  if (diff === 0) return 'Material is roughly even';
  const leader = diff > 0 ? 'White' : 'Black';
  const gap = Math.abs(diff);
  let amount;
  if (gap <= 1) amount = 'a pawn';
  else if (gap <= 3) amount = 'a piece';
  else if (gap <= 5) amount = 'the exchange';
  else amount = 'a lot of material';
  return `${leader} is up ${amount}`;
}

// Builds the SYSTEM prompt fed once per conversation to `chat_reset`. It frames
// the personality for CONVERSATION (not just trash talk): stay in character AND
// engage with what the opponent says and the position. This is prefilled into
// the persistent KV cache ONCE — it is NOT repeated each turn.
function buildSystemPrompt(personalityKey) {
  const key = PERSONALITIES[personalityKey] ? personalityKey : DEFAULT_PERSONALITY;
  const persona = PERSONALITIES[key].system;
  // BANTER framing. The small model produces move-notation GARBAGE when the
  // prompt invites real chess analysis, so we explicitly steer AWAY from it.
  return (
    `${persona} You are chatting during a chess game. Reply with ONE short, ` +
    `in-character sentence of banter. Do not give real chess analysis or ` +
    `move lists.`
  );
}

// Builds the per-turn TEXT sent to `chat_send`. NATURAL LANGUAGE ONLY — no
// parenthetical, no raw UCI/FEN, no move lists. Raw move notation in the prompt
// primes the small model to emit move-notation GARBAGE, so we NEVER include it.
// The system prompt and prior turns are already in the KV cache, so the turn is
// just the user's message itself, optionally with a SHORT natural note when the
// bot holds a clear material lead (e.g. "You're winning on material. ").
function buildUserTurn({ materialSummary, userMessage }) {
  const clean = String(userMessage || '').replace(/\s+/g, ' ').trim().slice(0, 80);
  // Only add a short natural note when the BOT (Black) leads on material — never
  // move notation. materialSummaryFromFen returns "Black is up ..." in that case.
  const botLeads = typeof materialSummary === 'string' && materialSummary.startsWith('Black is up');
  const prefix = botLeads ? "You're winning on material. " : '';
  return `${prefix}${clean}`;
}

// Builds the per-turn TEXT for a capture event. NATURAL LANGUAGE — a plain
// sentence, no parenthetical, no move notation. Described from the bot's point
// of view so "you"/"my"/"I"/"your" read naturally in the cached conversation.
// `byBot` true => the bot captured the player's piece (bot won the exchange).
function buildCaptureTurn(capture) {
  const piece = PIECE_LABEL[capture?.victim?.pieceType] || 'piece';
  if (capture?.byBot) {
    // The bot captured the opponent's piece (bot won).
    return `I just captured your ${piece}!`;
  }
  // The opponent captured the bot's piece (bot lost).
  return `You just captured my ${piece}!`;
}

// --- Output trimming ------------------------------------------------------
// The raw `generate` returns up to maxTokens and may ramble. Trim to ONE short
// line: cut at the first newline, then after the first sentence-ending
// punctuation, then hard-cap the length.
function trimToOneLine(raw) {
  if (!raw) return '';

  // The mock sentinel is a TEST STUB that must pass through unchanged (it has
  // non-letter brackets that the junk filters below would otherwise strip). Any
  // downstream trimming/suppression would break the deterministic e2e, so we
  // short-circuit BEFORE touching it.
  if (String(raw) === MOCK_REPLY) return MOCK_REPLY;

  let text = String(raw).trim();

  // Strip anything the model might echo of the template markers.
  const marker = text.indexOf('BITNETAssistant:');
  if (marker !== -1) text = text.slice(marker + 'BITNETAssistant:'.length).trim();

  // Cut at the first newline (one line only).
  const nl = text.indexOf('\n');
  if (nl !== -1) text = text.slice(0, nl).trim();

  // The small model likes to prefix replies with a list marker ("1. ", "1) ",
  // "- ", "* ") or wrap them in quotes. Strip those first so we don't end up
  // cutting the "sentence" off at the "1." and returning just "1.".
  text = text.replace(/^["'“”\s]+/, '');
  // Strip one or more leading enumeration / bullet markers.
  let prev;
  do {
    prev = text;
    text = text.replace(/^\s*\d+\s*[.)]\s*/, '').replace(/^\s*[-*•]\s*/, '');
  } while (text !== prev);

  // --- SALVAGE JUNK PREFIXES ------------------------------------------------
  // The model puts a junk prefix on some turns ("0n't 1, but I'm the best in
  // chess!"). Drop leading "junk" tokens until we reach a real word, so we keep
  // the salvageable tail ("but I'm the best in chess!").
  //
  // 1. Strip leading quotes/whitespace (already mostly done above; be thorough).
  text = text.replace(/^["'“”\s]+/, '');
  // 2. A token is JUNK if it contains a digit, OR has < 2 letters, OR is > 50%
  //    non-letter characters. Drop leading junk tokens until we hit a token that
  //    starts with a letter, has >= 2 letters, and has no digit. Rejoin there.
  const tokens = text.split(/\s+/).filter(Boolean);
  const letterCount = (t) => (t.match(/[A-Za-z]/g) || []).length;
  const isJunk = (t) => {
    if (/\d/.test(t)) return true; // contains a digit
    if (letterCount(t) < 2) return true; // fewer than 2 letters
    if (letterCount(t) / t.length <= 0.5) return true; // > 50% non-letter
    return false;
  };
  const isCleanStart = (t) => /^[A-Za-z]/.test(t) && letterCount(t) >= 2 && !/\d/.test(t);
  let start = 0;
  while (start < tokens.length && !isCleanStart(tokens[start]) && isJunk(tokens[start])) {
    start++;
  }
  text = tokens.slice(start).join(' ');

  // 3. Take the first sentence, requiring a few real characters before the
  //    terminator so a stray "." doesn't yield an empty/one-char reply.
  const m = text.match(/^[\s\S]{3,}?[.!?](\s|$)/);
  if (m) text = m[0].trim();

  // Drop surrounding quotes the model sometimes adds.
  text = text.replace(/^["'“”]+/, '').replace(/["'“”]+$/, '').trim();

  // 4. Capitalize the first letter.
  if (text.length > 0) {
    text = text.charAt(0).toUpperCase() + text.slice(1);
  }

  // Hard cap length as a final safety net.
  if (text.length > MAX_REPLY_CHARS) {
    text = text.slice(0, MAX_REPLY_CHARS).trim();
  }

  // 5. FINAL JUNK CHECK: reject replies that are still mostly noise. A reply is
  //    junk if it has fewer than 2 alphabetic words (>= 2 letters each) OR is
  //    more than 35% non-letter/space characters. Return '' so the caller can
  //    suppress it (never show hardcoded phrasing).
  const words = text.split(/\s+/).filter((w) => letterCount(w) >= 2);
  if (words.length < 2) return '';
  const nonLetterSpace = (text.match(/[^A-Za-z\s]/g) || []).length;
  if (text.length > 0 && nonLetterSpace / text.length > 0.35) return '';

  return text;
}

// --- Worker singleton + warming-up status ---------------------------------
const worker = {
  instance: null,
  ready: false,
  loadStarted: false,
  loadFailed: false,
  nextId: 1,
  pending: new Map(), // id -> { resolve, reject }
};

// --- Conversation state (stateful chat session) ---------------------------
// The system prompt currently applied to the worker's KV cache, or null if no
// conversation has been started yet. When `pendingSystem` differs from this we
// (re)issue a `chat_reset` before the next `chat_send`.
let activeSystem = null;
// The system prompt we WANT applied. Set by resetConversation(); may be pending
// if the model isn't ready yet (applied lazily on first use). Defaults to the
// stored/default personality so the first message always has a persona.
let pendingSystem = buildSystemPrompt(DEFAULT_PERSONALITY);

// Send the pending `chat_reset` to the worker if it differs from what's applied.
// No-op unless the model is ready. Safe to call repeatedly (idempotent).
function ensureConversation() {
  if (!worker.ready || !worker.instance) return;
  if (pendingSystem === activeSystem) return;
  worker.instance.postMessage({ type: 'chat_reset', system: pendingSystem });
  activeSystem = pendingSystem;
}

/**
 * Start a FRESH conversation with the given personality's system prompt. Resets
 * the KV cache so the persona actually changes and prior turns are forgotten —
 * call this on personality change AND on New Game / board reset.
 *
 * Lazy: if the model isn't ready yet the reset is recorded and applied on the
 * first `generateReply` after it becomes ready.
 *
 * @param {string} personality - a key of PERSONALITIES.
 */
export function resetConversation(personality) {
  const key = PERSONALITIES[personality] ? personality : DEFAULT_PERSONALITY;
  pendingSystem = buildSystemPrompt(key);
  if (forceMock()) return; // mock has no worker/session
  ensureWorker();
  ensureConversation();
}

// Current warming-up status string (neutral, NOT in character), or null once
// ready/failed. Read via getLLMStatusText().
let warmingUpStatus = null;
// Progress bytes (best-effort) for a friendly percentage.
let loadedBytes = 0;
let totalBytes = 0; // from manifest if available

function updateWarmingUpStatus() {
  if (worker.ready || worker.loadFailed) {
    warmingUpStatus = null;
    return;
  }
  if (totalBytes > 0 && loadedBytes > 0) {
    const mb = Math.round(loadedBytes / 1e6);
    const totalMb = Math.round(totalBytes / 1e6);
    if (loadedBytes >= totalBytes) {
      // Download done; the wasm is decoding the model into memory.
      warmingUpStatus = '🧠 Loading the bot’s brain into memory…';
    } else {
      const pct = Math.min(99, Math.floor((loadedBytes / totalBytes) * 100));
      warmingUpStatus = `🧠 Downloading the bot’s brain… ${mb}/${totalMb} MB (${pct}%)`;
    }
  } else {
    warmingUpStatus = '🧠 Bot is warming up…';
  }
}

/** Has the model finished loading and is ready to generate? */
export function isLLMReady() {
  if (forceMock()) return true; // mock is instantly "ready"
  return !!(worker.instance && worker.ready && !worker.loadFailed);
}

/**
 * The current neutral warming-up status line, or null when there's nothing to
 * show (ready, failed, or mock). Never an in-character phrase.
 */
export function getLLMStatusText() {
  if (forceMock()) return null;
  if (worker.loadFailed) return '🧠 Bot is offline (model unavailable).';
  return warmingUpStatus;
}

// Fetch the model manifest and return { urls, sizes } (same-origin). `sizes`
// (per-chunk byte lengths) lets the worker download chunks in parallel and place
// each at its correct offset.
async function loadManifest(base) {
  const url = `${base}bitnet/model/manifest.json`;
  const resp = await fetch(url);
  if (!resp.ok) throw new Error(`manifest fetch failed: HTTP ${resp.status}`);
  const data = await resp.json();
  const chunks = Array.isArray(data.chunks) ? data.chunks : [];
  const sizes = Array.isArray(data.sizes) ? data.sizes : null;
  if (typeof data.bytes === 'number' && data.bytes > 0) totalBytes = data.bytes;
  return { urls: chunks.map((c) => `${base}bitnet/model/${c}`), sizes };
}

// Lazily create the worker and start loading the model exactly once.
function ensureWorker() {
  if (worker.instance || worker.loadStarted) return;
  worker.loadStarted = true;

  const base = resolveBase();

  try {
    worker.instance = new Worker(`${base}bitnet/llm-worker.js`, { type: 'module' });
  } catch (e) {
    worker.loadFailed = true;
    updateWarmingUpStatus();
    console.warn('bitnet worker could not start:', e);
    return;
  }

  warmingUpStatus = '🧠 Bot is warming up…';

  worker.instance.onmessage = (e) => {
    const msg = e.data || {};
    if (msg.type === 'progress') {
      loadedBytes = msg.loaded || loadedBytes;
      if (!totalBytes && msg.total) totalBytes = msg.total;
      updateWarmingUpStatus();
    } else if (msg.type === 'ready') {
      worker.ready = true;
      updateWarmingUpStatus();
      // Apply the (possibly deferred) system prompt now that the session exists,
      // so the first `chat_send` always runs against the right persona.
      ensureConversation();
    } else if (msg.type === 'reset_done') {
      // Acknowledgement only; the session is already tracked via activeSystem.
    } else if (msg.type === 'result') {
      const p = worker.pending.get(msg.id);
      if (p) {
        worker.pending.delete(msg.id);
        p.resolve(trimToOneLine(msg.text) || null);
      }
    } else if (msg.type === 'error') {
      console.warn('bitnet worker error:', msg.message);
      if (msg.id != null) {
        const p = worker.pending.get(msg.id);
        if (p) {
          worker.pending.delete(msg.id);
          p.reject(new Error(msg.message));
        }
      } else {
        // Load-time error: give up on the model. No fake quips — status only.
        worker.loadFailed = true;
        updateWarmingUpStatus();
      }
    }
  };

  worker.instance.onerror = (e) => {
    worker.loadFailed = true;
    updateWarmingUpStatus();
    console.warn('bitnet worker crashed:', e.message || e);
  };

  // Kick off the load: read the manifest, then tell the worker to fetch chunks.
  (async () => {
    try {
      const { urls: modelUrls, sizes } = await loadManifest(base);
      if (modelUrls.length === 0) {
        // Placeholder manifest / model not yet published. No fake output —
        // mark offline so the UI shows an honest status, never a canned quip.
        worker.loadFailed = true;
        updateWarmingUpStatus();
        return;
      }
      updateWarmingUpStatus();
      worker.instance.postMessage({
        type: 'load',
        modelUrls,
        // Known total size from the manifest's `bytes` field. The worker uses
        // this to preallocate ONE output buffer instead of holding every chunk
        // plus a second concatenated copy in memory at once.
        totalBytes,
        // Per-chunk sizes let the worker fetch chunks in PARALLEL, writing each
        // into the preallocated buffer at its correct offset.
        sizes,
        wasmBindingsUrl: `${base}bitnet/bitnet_wasm.js`,
        wasmUrl: `${base}bitnet/bitnet_wasm_bg.wasm`,
      });
    } catch (err) {
      worker.loadFailed = true;
      updateWarmingUpStatus();
      console.warn('bitnet model load could not start:', err);
    }
  })();
}

// Feed ONE new turn to the stateful session; resolves with the trimmed reply
// (or null). Turns are serialized IN ORDER by the worker's queue, so rapid
// user messages stay ordered and the KV cache never sees turns out of sequence.
function requestChatTurn(text) {
  return new Promise((resolve, reject) => {
    const id = worker.nextId++;
    worker.pending.set(id, { resolve, reject });
    worker.instance.postMessage({
      type: 'chat_send',
      id,
      text,
      maxTokens: MAX_TOKENS,
      // Balanced sampling + a FRESH random seed per turn. The worker applies
      // these via model.set_sampling(...) right before chat_send.
      temperature: SAMPLING.temperature,
      topK: SAMPLING.topK,
      topP: SAMPLING.topP,
      repeatPenalty: SAMPLING.repeatPenalty,
      seed: freshSeed(),
    });
  });
}

/**
 * Pre-warm the on-device LLM: create the worker and begin model download so
 * it's ready as soon as possible. Safe to call on page load — fully async,
 * never blocks, and no-ops in force-mock mode.
 */
export function preloadLLM() {
  if (forceMock()) return;
  ensureWorker();
}

/**
 * Generate a short, in-character reply from board context.
 *
 * EXACTLY ONE of `capture` / `userMessage` should be provided:
 *   - capture:      react to a just-happened capture (bot-initiated banter).
 *   - userMessage:  reply to what the user typed in the chat input.
 *
 * @param {Object} args
 * @param {string}  args.personality  - a key of PERSONALITIES (e.g. 'sassy').
 * @param {string[]}[args.moves]      - recent moves (short UCI/SAN strings).
 * @param {string} [args.fen]         - current board FEN.
 * @param {string} [args.userMessage] - the user's chat message (chat path).
 * @param {Object} [args.capture]     - a capture event { victim:{pieceType}, byBot }.
 * @returns {Promise<string|null>} the trimmed reply, or null if the model isn't
 *          ready yet (caller shows warming-up status or skips).
 */
export async function generateReply({ personality, moves, fen, userMessage, capture }) {
  const key = PERSONALITIES[personality] ? personality : DEFAULT_PERSONALITY;

  // Deterministic sentinel for e2e / forced mock. Never a product phrase.
  if (forceMock()) return MOCK_REPLY;

  ensureWorker();

  // Model not ready yet (loading, failed, or empty manifest). Return null and
  // let the caller decide (skip capture-banter; show warming-up for chat).
  if (!isLLMReady()) return null;

  // LAZY FIRST RESET: make sure a conversation is established with the right
  // persona BEFORE the first turn. If resetConversation() was never called,
  // pendingSystem already defaults to the caller's personality below; if a
  // caller passes a personality that differs from the active session (e.g. a
  // capture fires before the selector wired a reset), switch to it here.
  const wantSystem = buildSystemPrompt(key);
  if (wantSystem !== activeSystem) {
    pendingSystem = wantSystem;
  }
  ensureConversation();

  // Build the SHORT per-turn text. The system prompt is cached (not repeated).
  // Material summary comes from the piece-placement field only — the raw FEN
  // (with castling "KQkq") is never included (it makes the small model loop).
  const materialSummary = materialSummaryFromFen(fen);
  const text =
    userMessage != null
      ? buildUserTurn({ materialSummary, userMessage })
      : buildCaptureTurn(capture);

  const reply = await requestChatTurn(text);
  return reply || null;
}
